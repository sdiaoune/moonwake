void level_load(uint8_t id, LevelDef *out, PlatformDef *plats,
                PickupDef *picks, EnemyDef *enemies) BANKED {
    if (id >= LEVEL_COUNT) id = 0u;
    memcpy(out, &definitions[id], sizeof(LevelDef));
    memcpy(plats, platform_sets[id], (uint16_t)out->platform_count * sizeof(PlatformDef));
    memcpy(picks, pickup_sets[id], (uint16_t)out->pickup_count * sizeof(PickupDef));
    memcpy(enemies, enemy_sets[id], (uint16_t)out->enemy_count * sizeof(EnemyDef));
}

